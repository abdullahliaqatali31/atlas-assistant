// Writes docs/THIRD_PARTY_LICENSES.md from the installed dependency tree.
//   pnpm licenses:inventory
// It lists every package used to build or run the app (a superset of what the
// installer ships), groups them by license and flags copyleft ones for review.
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const raw = JSON.parse(execSync('pnpm licenses list --json', { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }))
const COPYLEFT = /GPL|MPL|EPL|CDDL|EUPL|OSL/i
const MODELS = [
  { name: 'Moonshine tiny (ONNX, quantized)', source: 'https://huggingface.co/onnx-community/moonshine-tiny-ONNX', license: 'MIT', use: 'Wake word detection, downloaded on request' },
  { name: 'ERes2Net base speaker model (3D-Speaker, ONNX via sherpa-onnx)', source: 'https://github.com/modelscope/3D-Speaker', license: 'Apache-2.0', use: 'Voice ID, downloaded when the owner sets up their voice' },
  { name: 'multilingual-e5-small (ONNX, quantized)', source: 'https://huggingface.co/Xenova/multilingual-e5-small', license: 'MIT', use: 'Recall by meaning, downloaded when turned on' },
]

const groups = Object.entries(raw).sort(([a], [b]) => raw[b].length - raw[a].length || a.localeCompare(b))
const total = groups.reduce((n, [, list]) => n + list.length, 0)
const lines = [
  '# Third-party licenses',
  '',
  `Generated by \`pnpm licenses:inventory\` on ${new Date().toISOString().slice(0, 10)}. ${total} packages are used to build or run Atlas; the release zip ships a subset of them, bundled into the app or installed beside it.`,
  '',
  'Atlas itself is licensed under Apache-2.0 (see LICENSE and NOTICE).',
  '',
  '## Needs review',
  '',
]
const review = groups.filter(([lic]) => COPYLEFT.test(lic))
if (review.length === 0) lines.push('No copyleft licenses found.')
for (const [lic, list] of review) {
  for (const p of list) lines.push(`- **${p.name}** ${p.versions.join(', ')} (${lic}): ${p.homepage ?? ''}`)
}
lines.push(
  '',
  'MPL-2.0 is file-level copyleft: using the package unmodified is fine; changes to its own files must stay MPL. LGPL components must stay replaceable; check whether they are shipped or only used at build time before each release.',
  '',
  '## Models downloaded at run time',
  '',
  ...MODELS.map(m => `- **${m.name}** (${m.license}): ${m.use}. ${m.source}`),
  '',
  '## Brand marks and bundled files',
  '',
  '- **Service logos** in `apps/desktop/src/renderer/src/ui/brands.ts`: from the "logos" collection by Gil Barbara (CC0-1.0), https://github.com/gilbarbara/logos. Each mark remains its owner\'s trademark and is shown only to name that service.',
  '- **Microsoft WebView2 SDK** (Microsoft.Web.WebView2.Core.dll, Microsoft.Web.WebView2.WinForms.dll, WebView2Loader.dll) in `apps/desktop/resources/webview2/`: BSD-style licence by Microsoft (kept beside the files), for the desktop widget on Windows.',
  '',
  '## Summary',
  '',
  '| License | Packages |',
  '|---|---|',
  ...groups.map(([lic, list]) => `| ${lic} | ${list.length} |`),
  '',
  '## All packages',
  '',
)
for (const [lic, list] of groups) {
  lines.push(`### ${lic}`, '')
  for (const p of [...list].sort((a, b) => a.name.localeCompare(b.name))) lines.push(`- ${p.name} ${p.versions.join(', ')}${p.author ? ` by ${String(p.author).replace(/\s*<[^>]*>/g, '')}` : ''}`)
  lines.push('')
}
writeFileSync('docs/THIRD_PARTY_LICENSES.md', lines.join('\n'))
console.log(`docs/THIRD_PARTY_LICENSES.md: ${total} packages, ${review.reduce((n, [, l]) => n + l.length, 0)} to review`)
