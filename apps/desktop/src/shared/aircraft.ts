/** What a transponder code means, when it is one of the three that matter. */
export const squawkMeaning = (squawk: string): string =>
  squawk === '7500' ? 'Hijack' : squawk === '7600' ? 'Radio failure' : squawk === '7700' ? 'General emergency' : ''
